import re, sys
src = open('node_modules/tailwindcss/theme.css').read()
pal = {}
for fam, shade, val in re.findall(r'--color-([a-z]+)-(\d+):\s*([^;]+);', src):
    pal.setdefault(fam, {})[int(shade)] = val.strip()
SH = [50,100,200,300,400,500,600,700,800,900,950]
ACCENTS = ['indigo','sky','emerald','rose','amber','purple','violet','fuchsia','pink','orange','teal','cyan','red','green','blue','yellow']

def block(sel, decls):
    return sel + ' {\n' + ''.join(f'  {k}: {v};\n' for k, v in decls) + '}\n'

# Dark (default): calmer neutrals (Tailwind gray instead of blue-tinted slate) and an enterprise blue brand accent.
dark = []
for s in SH:
    dark.append((f'--color-slate-{s}', pal['gray'][s]))
    dark.append((f'--color-indigo-{s}', pal['blue'][s]))
dark += [('--az-canvas', '#0e1116'), ('--az-sidebar', '#11151b'), ('--az-surface', '#151a21'), ('--az-raised', '#1b212a'),
         ('--az-raised-hover', '#212833'), ('--az-sunken', '#0b0e12'), ('--az-code', '#0a0d11'), ('--az-scrim', 'rgb(3 6 10 / 0.6)'),
         ('--az-shadow', '0 1px 2px rgb(0 0 0 / 0.3)'), ('color-scheme', 'dark')]

# Light: mirror neutral scale fully (text ↔ backgrounds); mirror accent text shades (100–400 → 900–600) but keep
# solid fills (500+) so buttons and dots keep their colour. "white" overlays become dark ink overlays.
light = []
mirror = {s: SH[len(SH)-1-i] for i, s in enumerate(SH)}
for s in SH:
    light.append((f'--color-slate-{s}', pal['gray'][mirror[s]]))
for fam in ACCENTS:
    base = pal['blue'] if fam == 'indigo' else pal[fam]
    for s in (50,100,200,300,400):
        light.append((f'--color-{fam}-{s}', base[mirror[s]]))
    if fam == 'indigo':
        for s in (500,600,700,800,900,950):
            light.append((f'--color-{fam}-{s}', base[s]))
light += [('--color-white', '#0f172a'), ('--az-canvas', '#f5f6f8'), ('--az-sidebar', '#ffffff'), ('--az-surface', '#ffffff'),
          ('--az-raised', '#ffffff'), ('--az-raised-hover', '#f3f4f6'), ('--az-sunken', '#eef0f3'), ('--az-code', '#f3f4f6'),
          ('--az-scrim', 'rgb(15 23 42 / 0.35)'), ('--az-shadow', '0 1px 2px rgb(15 23 42 / 0.06), 0 1px 3px rgb(15 23 42 / 0.05)'), ('color-scheme', 'light')]

out = ['/* GENERATED by scripts/gen_theme.py from Tailwind\'s palette — do not edit by hand. */',
       '/* Dark is the default; [data-theme="light"] mirrors the scales so every component themes without class changes. */', '']
out.append('@theme inline {\n  --color-canvas: var(--az-canvas);\n  --color-sidebar: var(--az-sidebar);\n  --color-surface: var(--az-surface);\n'
           '  --color-raised: var(--az-raised);\n  --color-raised-hover: var(--az-raised-hover);\n  --color-sunken: var(--az-sunken);\n'
           '  --color-code: var(--az-code);\n  --color-scrim: var(--az-scrim);\n  --color-onaccent: #ffffff;\n  --shadow-card: var(--az-shadow);\n}\n')
out.append(block(':root', dark))
out.append(block(':root[data-theme="light"]', light))
open(sys.argv[1], 'w').write('\n'.join(out))
print('wrote', sys.argv[1], len(dark), 'dark vars', len(light), 'light vars')
